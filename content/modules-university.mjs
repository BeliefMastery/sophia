/** University-path 101 modules. Delivered first at Year 11 (about age 16); later modules deepen toward university. */

import { buildPassage } from "../lib/passage.mjs";

function q(entry) {
  const item = {
    kind: "probe",
    answerKind: "choice",
    ideaId: entry.id,
    ...entry,
  };
  if (!Array.isArray(item.passage) || item.passage.length !== 2) {
    item.passage = buildPassage(item);
  }
  return item;
}

function block(id, title, domain, order, summary, field) {
  return {
    id,
    title,
    domain,
    phase: "university-path",
    order,
    summary,
    depth: 2,
    role: "module",
    ageTier: "year11",
    field,
    continues: "placement-check",
  };
}

function pack(strandId, field, rows) {
  return rows.map((row, index) => q({
    id: `${strandId}-${index + 1}`,
    strandId,
    claim: field,
    order: index + 1,
    prompt: row.prompt,
    choices: row.choices,
    answer: row.answer,
    lookFor: row.lookFor,
    misconceptions: row.misconceptions,
    followPrompt: row.follow,
    repairAccept: row.accept,
    discover: [{ label: `search: ${row.topic || field} 101` }],
  }));
}

