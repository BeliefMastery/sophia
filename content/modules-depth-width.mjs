import { buildPassage } from "../lib/passage.mjs";

function q(entry) {
  const item = {
    kind: "probe",
    answerKind: "choice",
    ideaId: entry.id,
    ...entry,
  };
  if (!item.passage) item.passage = buildPassage(item);
  return item;
}

function strand(spec) {
  return {
    role: "module",
    ...spec,
  };
}

function pack(strandId, claim, rows) {
  return rows.map((row, index) => q({
    id: `${strandId}-${index + 1}`,
    strandId,
    claim,
    order: index + 1,
    ...row,
  }));
}

